function shuffle<T>(arr: T[]): T[] {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

function getMessagePool(type: BcrEventType): string[] {
  const minLen = 5;
  switch (type) {
    case "win":
      return WIN_MESSAGES.filter((m) => m.trim().length >= minLen);
    case "draw":
      return DRAW_MESSAGES.filter((m) => m.trim().length >= minLen);
    case "lose":
      return [...LOSE_MESSAGES, ...GROUP_HALL_QUESTIONS].filter(
        (m) => m.trim().length >= minLen
      );
    case "qa":
      return [];
  }
}

/** Chọn câu không trùng trong cùng một ca / kịch bản */
export function pickUniqueBcrMessages(
  type: BcrEventType,
  count: number,
  exclude: Set<string> = new Set()
): string[] {
  const pool = shuffle(getMessagePool(type).filter((m) => !exclude.has(m)));
  const result: string[] = [];

  for (const message of pool) {
    if (result.length >= count) break;
    if (!result.includes(message)) result.push(message);
  }

  let guard = 0;
  while (result.length < count && guard < 8) {
    guard++;
    for (const message of shuffle(getMessagePool(type))) {
      if (result.length >= count) break;
      if (!result.includes(message) && !exclude.has(message)) {
        result.push(message);
      }
    }
  }

  return humanizeMessages(result.slice(0, count));
}

export function getBcrMessages(type: BcrEventType, count = 100): string[] {
  return pickUniqueBcrMessages(type, count);
}

export function getBcrFollowUp(
  type: "win" | "draw" | "lose",
  index: number
): string {
  const pool = FOLLOW_UP[type];
  return maybeApplyTypos(pool[index % pool.length]);
}

